  function(method_id, question = NULL) {
    if (!is.character(method_id) || length(method_id) != 1L ||
        is.na(method_id) || !validUTF8(method_id) ||
        !method_id %in% names(entries)) return(NULL)
    if (!is.null(question) &&
        (!is.character(question) || length(question) != 1L ||
         is.na(question) || !validUTF8(question) ||
         nchar(question, type = "bytes") > 4096L))
      return(NULL)
    item <- entries[[method_id]]
    # The guide is conceptual. Its static synthetic example has NOT been run.
    # The student must supply real data and explicitly invoke ru_apply().

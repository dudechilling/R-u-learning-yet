                  item$code, "\nThen: ", item$steps[[3L]])
    )
    list(
      schema_version = "ru.w5.method-guide.v1",
      status = "GUIDED_REFERENCE",
      method_id = item$id,
      question = question,
      title = item$title,
      required_inputs = item$required,
      why_this_method = item$idea,

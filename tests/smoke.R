library(rulearn)
db <- getFromNamespace(".ru_db","rulearn")("problems.csv")
routes <- getFromNamespace(".ru_db","rulearn")("routes.csv")
stopifnot(nrow(db)>=40L,!anyDuplicated(db$id))
stopifnot(all(db$id %in% routes$id))
stopifnot(identical(ru_find("histogram",n=1)$id,"histogram"))
p <- capture.output(ru_plan("histogram",have=c("numeric","units"),missing="groups"))
stopifnot(any(grepl("Selected route",p,fixed=TRUE)))
u <- capture.output(ru_plan("histogram",have=c("numeric")))
stopifnot(!any(grepl("missing [groups]",u,fixed=TRUE)))
err <- try(ru_plan("histogram",have="numeric",missing="numeric"),silent=TRUE)
stopifnot(inherits(err,"try-error"))
stopifnot(all(nzchar(vapply(db$id,function(id) {
  system.file("examples",paste0(id,".R"),package="rulearn")
},character(1L)))))
for (id in db$id) {
  f <- tempfile(fileext=".pdf")
  grDevices::pdf(f,width=8,height=6)
  result <- try(suppressWarnings(capture.output(ru_run(id))),silent=TRUE)
  grDevices::dev.off()
  if (inherits(result,"try-error")) stop(id,": ",as.character(result))
  if (file.exists(f)) unlink(f)
}
f <- tempfile(fileext=".pdf")
grDevices::pdf(f)
ru_hist(c(1,2,2,3,4),units="Units")
ru_bar(c("A","B","A"))
ru_box(c(2,3,4,5,20))
ru_box(c(2,3,4,5,20,21),groups=c("A","A","A","B","B","B"))
ru_scatter(1:5,c(2,5,4,8,11))
grDevices::dev.off()
unlink(f)
cat("Smoke checks passed: ",nrow(db)," runnable examples.\n",sep="")
